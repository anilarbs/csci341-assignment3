CREATE TABLE app_user (
    user_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    given_name text NOT NULL, surname text NOT NULL, email text NOT NULL UNIQUE,
    affiliation text NOT NULL, country text NOT NULL, phone_number text NOT NULL
);
CREATE TABLE author (
    author_id integer PRIMARY KEY REFERENCES app_user ON DELETE CASCADE, orcid text
);
CREATE TABLE author_research_area (
    author_id integer REFERENCES author ON DELETE CASCADE, area_label text,
    PRIMARY KEY (author_id, area_label)
);
CREATE TABLE reviewer (
    reviewer_id integer PRIMARY KEY REFERENCES app_user ON DELETE CASCADE,
    years_experience integer NOT NULL CHECK (years_experience >= 0)
);
CREATE TABLE reviewer_expertise (
    reviewer_id integer REFERENCES reviewer ON DELETE CASCADE, area_label text,
    PRIMARY KEY (reviewer_id, area_label)
);
CREATE TABLE conference (
    conference_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL, acronym text NOT NULL, description text NOT NULL, city text NOT NULL,
    country text NOT NULL, start_date date NOT NULL, end_date date NOT NULL,
    submission_deadline date NOT NULL, review_deadline date NOT NULL,
    CHECK (end_date >= start_date)
);
CREATE TABLE conference_host (
    conference_id integer REFERENCES conference ON DELETE CASCADE, host_name text,
    PRIMARY KEY (conference_id, host_name)
);
CREATE TABLE conference_reviewer (
    conference_id integer REFERENCES conference ON DELETE CASCADE,
    reviewer_id integer REFERENCES reviewer, PRIMARY KEY (conference_id, reviewer_id)
);
CREATE TABLE track (
    track_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conference_id integer NOT NULL REFERENCES conference, name text NOT NULL,
    description text NOT NULL, research_area text NOT NULL, coordinator_id integer NOT NULL REFERENCES reviewer,
    FOREIGN KEY (conference_id, coordinator_id) REFERENCES conference_reviewer
);
CREATE TABLE conference_session (
    session_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conference_id integer NOT NULL REFERENCES conference, title text NOT NULL,
    session_date date NOT NULL, start_time time NOT NULL, end_time time NOT NULL,
    room_label text NOT NULL, chair_id integer NOT NULL REFERENCES reviewer,
    FOREIGN KEY (conference_id, chair_id) REFERENCES conference_reviewer,
    CHECK (end_time > start_time)
);
CREATE TABLE paper (
    paper_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    track_id integer NOT NULL REFERENCES track, title text NOT NULL, abstract text NOT NULL,
    submission_date date NOT NULL, status text NOT NULL
    CHECK (status IN ('submitted','under review','accepted','rejected','withdrawn')),
    session_id integer REFERENCES conference_session ON DELETE SET NULL
);
CREATE TABLE paper_keyword (
    paper_id integer REFERENCES paper ON DELETE CASCADE, keyword text, PRIMARY KEY (paper_id, keyword)
);
CREATE TABLE paper_author (
    paper_id integer REFERENCES paper ON DELETE CASCADE, author_id integer REFERENCES author,
    author_position integer NOT NULL CHECK (author_position > 0), is_corresponding boolean NOT NULL,
    PRIMARY KEY (paper_id, author_id), UNIQUE (paper_id, author_position)
);
CREATE UNIQUE INDEX one_corresponding ON paper_author (paper_id) WHERE is_corresponding;
CREATE TABLE paper_version (
    paper_id integer REFERENCES paper ON DELETE CASCADE, version_no integer CHECK (version_no > 0),
    file_location text NOT NULL, uploaded_at timestamp NOT NULL, change_note text,
    PRIMARY KEY (paper_id, version_no)
);
CREATE TABLE review (
    review_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paper_id integer NOT NULL REFERENCES paper ON DELETE CASCADE, reviewer_id integer NOT NULL REFERENCES reviewer,
    overall_score integer NOT NULL CHECK (overall_score BETWEEN 1 AND 5),
    recommendation text NOT NULL CHECK (recommendation IN ('accept','reject')),
    comments_for_authors text NOT NULL, confidential_comments text, review_submission_date date NOT NULL,
    UNIQUE (paper_id, reviewer_id)
);
